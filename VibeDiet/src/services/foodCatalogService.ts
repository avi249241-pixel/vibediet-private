// 3. IN-MEMORY CACHE FOR PROXIED QUERIES & LIVE LOOKUPS
// =========================================================================

const barcodeCache = new Map<string, FoodItemEntry>();
const searchCache = new Map<string, FoodItemEntry[]>();

// Seed cache with pre-verified barcodes
for (const [code, item] of Object.entries(VERIFIED_BARCODE_MAP)) {
  barcodeCache.set(code, item);
}

// =========================================================================
// 4. HYBRID 3-LAYER FOOD SEARCH & BARCODE SERVICE
// =========================================================================

export const foodCatalogService = {
  /**
   * Layer 1: Instant search across local IFCT/USDA catalog
   */
  searchLocal(query: string): FoodItemEntry[] {
    const clean = query.trim().toLowerCase();
    if (!clean) return [...LOCAL_VERIFIED_CATALOG];

    return LOCAL_VERIFIED_CATALOG.filter((item) =>
      item.name.toLowerCase().includes(clean)
    );
  },

  /**
   * Layer 2 & 3: Live query search merging instant local matches with cached / USDA results
   */
  async searchFoods(query: string, timeoutMs = 2500): Promise<FoodItemEntry[]> {
    const clean = query.trim();
    if (!clean) {
      return [...LOCAL_VERIFIED_CATALOG];
    }

    const localMatches = this.searchLocal(clean);

    // Check query cache
    const cacheKey = clean.toLowerCase();
    if (searchCache.has(cacheKey)) {
      return searchCache.get(cacheKey)!;
    }

    // Attempt live USDA search if query is specific and offline tests are not active
    try {
      let liveResults: FoodItemEntry[] = [];
      if (typeof window !== 'undefined') {
        const res = await fetch(`/v1/foods/search?q=${encodeURIComponent(clean)}`);
        if (res.ok) {
          const json = await res.json();
          liveResults = json.data || [];
        }
      } else {
        const apiModulePath = './apiConnectors.js';
        const { searchUsdaFoods } = await import(/* @vite-ignore */ apiModulePath);
        const abortCtrl = new AbortController();
        const timer = setTimeout(() => abortCtrl.abort(), timeoutMs);

        liveResults = await Promise.race([
          searchUsdaFoods(clean),
          new Promise<never>((_, reject) => {
            abortCtrl.signal.addEventListener('abort', () => reject(new Error('USDA timeout')));
          }),
        ]);
        clearTimeout(timer);
      }

      // Merge results without duplicates
      const merged = [...localMatches];
      for (const liveItem of liveResults) {
        if (!merged.some((m) => m.name.toLowerCase() === liveItem.name.toLowerCase())) {
          merged.push(liveItem);
        }
      }

      searchCache.set(cacheKey, merged);
      return merged;
    } catch {
      // Fall back seamlessly to local catalog
      return localMatches;
    }
  },

  /**
   * Layer 2: Live barcode lookup with 4s timeout, Atwater reconciliation & caching
   */
  async lookupBarcode(barcode: string, timeoutMs = 4000): Promise<FoodItemEntry | null> {
    const cleanCode = barcode.replace(/[\s-]/g, '').trim();
    if (!cleanCode) return null;

    // Check code directly, or 13-digit EAN padded with leading 0 if 12-digit UPC
    const candidateCodes = [cleanCode];
    if (cleanCode.length === 12 && /^\d+$/.test(cleanCode)) {
      candidateCodes.push(`0${cleanCode}`);
    }
    if (cleanCode.length === 13 && cleanCode.startsWith('0')) {
      candidateCodes.push(cleanCode.slice(1));
    }

    // 1. Check local pre-verified barcode catalog and cache
    for (const code of candidateCodes) {
      if (barcodeCache.has(code)) {
        return barcodeCache.get(code)!;
      }
      if (VERIFIED_BARCODE_MAP[code]) {
        const item = VERIFIED_BARCODE_MAP[code];
        barcodeCache.set(cleanCode, item);
        return item;
      }
    }

    // 2. Live OpenFoodFacts API query with 4s timeout
    try {
      const url = `https://world.openfoodfacts.org/api/v2/product/${encodeURIComponent(cleanCode)}.json`;
      const userAgent =
        (typeof process !== 'undefined' && process.env && process.env.OPEN_FOOD_FACTS_USER_AGENT)
          ? process.env.OPEN_FOOD_FACTS_USER_AGENT
          : 'VibeDiet-App/2.0';
      const res = await fetch(url, {
        headers: { 'User-Agent': userAgent },
        signal: AbortSignal.timeout(timeoutMs),
      });

      if (!res.ok) return null;

      const raw = await res.json();
      if (!raw?.product) return null;

      const p = raw.product;
      const nutriments = p.nutriments || {};
      const brandStr = p.brands || '';
      const nameStr = p.product_name || `Barcode Item #${cleanCode}`;
      const fullName = [brandStr, nameStr].filter(Boolean).join(' ');

      const reportedCalories = Math.round(
        nutriments['energy-kcal_100g'] || nutriments['energy-kcal'] || 0
      );
      const protein = Number((nutriments.proteins_100g || nutriments.proteins || 0).toFixed(1));
      const carbs = Number((nutriments.carbohydrates_100g || nutriments.carbohydrates || 0).toFixed(1));
      const fat = Number((nutriments.fat_100g || nutriments.fat || 0).toFixed(1));
      const fiber = Number((nutriments.fiber_100g || nutriments.fiber || 0).toFixed(1));
      const sugar = Number((nutriments.sugars_100g || nutriments.sugars || 0).toFixed(1));
      const sodiumMg = Math.round(
        (nutriments.sodium_100g || nutriments.sodium || 0) * 1000
      );

      const normalized = normalizeFoodItem({
        id: `barcode-${cleanCode}`,
        name: fullName,
        grams: 100,
        tier: 2,
        tierSource: `Open Food Facts Barcode #${cleanCode}`,
        confidence: 0.96,
        reportedCalories,
        protein,
        carbs,
        fat,
        fiber,
        sugar,
        sodium: sodiumMg,
        barcode: cleanCode,
        cookingFatCategory: 'observable_low',
      });

      // Cache verified result locally
      barcodeCache.set(cleanCode, normalized);
      return normalized;
    } catch {
      return null;
    }
  },
};
